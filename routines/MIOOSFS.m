	SET ERR("routine")="MIOOSFS",OUTID=""
	SET PATH=$GET(PATH)
	IF PATH="" SET ERR("error")="path_missing" QUIT 0
	IF $$EXISTS(PATH) SET OUTID=PATH QUIT 1
	IF PATH="root" SET OUTID="root" QUIT 1
	IF PATH="Home"!(PATH="/Home") SET OUTID=$$HOMEID() QUIT $SELECT(OUTID'="":1,1:0)
	IF PATH="Documents"!(PATH="/Documents") SET OUTID=$$HOMEID() QUIT $SELECT(OUTID'="":1,1:0)
	IF PATH="Desktop"!(PATH="/Desktop") SET OUTID=$$DESKTOPID() QUIT $SELECT(OUTID'="":1,1:0)
	IF $EXTRACT(PATH,1)'="/" SET PATH="/"_PATH
	SET NODE="root"
	IF PATH="/" SET OUTID=NODE QUIT 1
	FOR I=2:1:$LENGTH(PATH,"/") DO  QUIT:NODE=""
	. SET NAME=$PIECE(PATH,"/",I)
	. QUIT:NAME=""
	. SET NODE=$GET(^MIO("MIOOS","FS","CHILD",NODE,NAME))
	. IF NODE'="",'$$EXISTS(NODE) SET NODE=""
	IF NODE="" SET ERR("error")="path_not_found",ERR("detail")=PATH QUIT 0
	SET OUTID=NODE
	QUIT 1
